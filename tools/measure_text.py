"""Regenerate src/diagr/layout/metrics.py from fonts installed on this machine.

Measures every printable ASCII character in headless Chrome for each family in the
default font stack and keeps the widest, so label pills never come out too short.

    python3 tools/measure_text.py /path/to/chrome
"""

import html
import json
import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
FAMILIES = ["-apple-system", "BlinkMacSystemFont", "Segoe UI", "Helvetica", "Arial"]
WEIGHTS = [400, 600]

PAGE = """<!doctype html><meta charset="utf-8"><body><script>
const families = %s, weights = %s, out = {};
const c = document.createElement("canvas").getContext("2d");
for (const w of weights) {
  const row = {};
  for (let code = 32; code < 127; code++) {
    const ch = String.fromCharCode(code);
    let best = 0;
    for (const f of families) { c.font = w + " 1000px '" + f + "'"; best = Math.max(best, c.measureText(ch).width); }
    row[ch] = Math.ceil(best);
  }
  let best = 0;
  for (const f of families) {
    c.font = w + " 1000px '" + f + "'"; best = Math.max(best, c.measureText("\\u2026").width);
  }
  row["\\u2026"] = Math.ceil(best);
  out[w] = row;
}
document.body.textContent = JSON.stringify(out);
</script>"""


def main(chrome):
    with tempfile.TemporaryDirectory() as tmp:
        page = pathlib.Path(tmp) / "measure.html"
        page.write_text(PAGE % (json.dumps(FAMILIES), json.dumps(WEIGHTS)))
        dom = subprocess.run(
            [chrome, "--headless=new", "--disable-gpu", f"--user-data-dir={tmp}/profile", "--dump-dom", page.as_uri()],
            capture_output=True,
            text=True,
            check=True,
        ).stdout
    data = json.loads(html.unescape(dom[dom.index("<body>") + 6 : dom.index("</body>")]))
    lines = [
        '"""Advance widths per 1000 units of font size, widest of the default font stack.',
        "",
        "Generated by tools/measure_text.py. Do not edit by hand.",
        '"""',
        "",
        "WIDTHS = {",
    ]
    for weight, row in data.items():
        lines.append(f"    {weight}: {{")
        items = [f"{json.dumps(ch, ensure_ascii=False)}: {w}" for ch, w in row.items()]
        for i in range(0, len(items), 8):
            lines.append("        " + ", ".join(items[i : i + 8]) + ",")
        lines.append("    },")
    lines.append("}")
    (ROOT / "src/diagr/layout/metrics.py").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome")
